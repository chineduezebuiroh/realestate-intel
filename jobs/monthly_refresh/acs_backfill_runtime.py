"""ACS backfill runtime profile and observations. Never reads provider/governance APIs."""
from __future__ import annotations

import argparse
import base64
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path, PurePosixPath
import platform
import subprocess
import sys
import tempfile
import zipfile

from core.source_artifacts.hashing import sha256_file, sha256_json

PROFILE_PATH = Path(__file__).with_name('acs_backfill_runtime_profile.json')


def profile() -> dict:
    # Code/workflow authority binds this exact file, not caller-selected policy.
    return json.loads(PROFILE_PATH.read_text())


def host() -> dict:
    return {'implementation': platform.python_implementation(),
            'python_version': platform.python_version(), 'system': platform.system(),
            'machine': platform.machine()}


def check_host(value: dict, policy: dict) -> None:
    for field in ('implementation', 'system', 'machine'):
        if value[field] != policy[field]:
            raise ValueError(f'ACS runtime drift: {field}')
    if value['python_version'] not in policy['python_versions']:
        raise ValueError('ACS runtime drift: python_version')


def verify_installed(distribution, name: str) -> str:
    record = distribution.read_text('RECORD')
    if record is None or distribution.files is None:
        raise ValueError(f'ACS runtime drift: distributions.{name}.installed_record_missing')
    for member in distribution.files:
        if member.hash is None:
            # RECORD and generated bytecode may legitimately be unhashed.
            if str(member).endswith('/RECORD') or (str(member).endswith('.pyc') and '__pycache__' in str(member)):
                continue
            raise ValueError(f'ACS runtime drift: distributions.{name}.unhashed_member')
        if member.hash.mode != 'sha256':
            raise ValueError(f'ACS runtime drift: distributions.{name}.hash_algorithm')
        path = Path(distribution.locate_file(member))
        actual = base64.urlsafe_b64encode(bytes.fromhex(sha256_file(path))).decode().rstrip('=')
        if actual != member.hash.value:
            raise ValueError(f'ACS runtime drift: distributions.{name}.installed_bytes')
    return record


def inspect_distribution(name: str, expected: dict, wheelhouse: Path) -> dict:
    wheel = wheelhouse / expected['wheel']
    if not wheel.is_file() or sha256_file(wheel) != expected['sha256']:
        raise ValueError(f'ACS runtime drift: distributions.{name}.wheel_sha256')
    distribution = importlib.metadata.distribution(name)
    if distribution.version != expected['version']:
        raise ValueError(f'ACS runtime drift: distributions.{name}.version')
    record = verify_installed(distribution, name)
    # Installed RECORD is not an authority for wheel payload bytes. Independently
    # compare every payload member to the separately hash-approved wheel. Pip may
    # regenerate only RECORD; generated scripts/metadata also undergo local checks.
    with zipfile.ZipFile(wheel) as archive:
        names = archive.namelist()
        if len(names) != len(set(names)):
            raise ValueError(f'ACS runtime drift: distributions.{name}.duplicate_wheel_member')
        for member in archive.infolist():
            path = PurePosixPath(member.filename)
            if path.is_absolute() or '..' in path.parts or any(part.endswith('.data') for part in path.parts):
                raise ValueError(f'ACS runtime drift: distributions.{name}.unsupported_wheel_layout')
            if member.is_dir() or member.filename.endswith('.dist-info/RECORD'):
                continue
            installed = Path(distribution.locate_file(member.filename))
            if not installed.is_file() or sha256_file(installed) != hashlib.sha256(archive.read(member)).hexdigest():
                raise ValueError(f'ACS runtime drift: distributions.{name}.wheel_payload')
    return {'version': distribution.version, 'wheel_sha256': expected['sha256'],
            'installed_record_sha256': hashlib.sha256(record.encode()).hexdigest()}


def observe() -> dict:
    policy = profile()
    observed = host()
    check_host(observed, policy)
    directory = os.environ.get('ACS_BACKFILL_WHEELHOUSE')
    if not directory:
        raise ValueError('ACS runtime drift: wheelhouse_missing')
    implementations = {name: inspect_distribution(name, expected, Path(directory))
                       for name, expected in policy['distributions'].items()}
    return {'schema_version': 'acs_backfill_runtime_observation_v1',
            'profile_sha256': sha256_json(policy), **observed,
            'python_full_version': sys.version,
            'python_executable_sha256': sha256_file(Path(sys.executable)),
            'implementations': implementations}


def compatibility_identity() -> dict:
    observed = observe()  # Always reverify the running installation, including at write fences.
    return {'schema_version': 'acs_backfill_runtime_compatibility_v1',
            'profile_sha256': observed['profile_sha256']}


def prepare(directory: Path) -> None:
    policy = profile()
    check_host(host(), policy)
    directory.mkdir(parents=True, exist_ok=False)
    with tempfile.TemporaryDirectory() as temp:
        lock = Path(temp) / 'requirements.txt'
        lock.write_text(''.join(f"{name}=={v['version']} --hash=sha256:{v['sha256']}\n"
                               for name, v in policy['distributions'].items()))
        subprocess.run([sys.executable, '-m', 'pip', 'download', '--only-binary=:all:',
                        '--no-deps', '--require-hashes', '-r', str(lock), '-d', str(directory)], check=True)
    wheels = []
    for expected in policy['distributions'].values():
        wheel = directory / expected['wheel']
        if not wheel.is_file() or sha256_file(wheel) != expected['sha256']:
            raise ValueError('ACS runtime drift: downloaded_wheel')
        wheels.append(str(wheel))
    subprocess.run([sys.executable, '-m', 'pip', 'install', '--no-index', '--no-deps',
                    '--force-reinstall', *wheels], check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--prepare', type=Path)
    mode.add_argument('--observe', type=Path)
    args = parser.parse_args()
    if args.prepare:
        prepare(args.prepare)
    else:
        value = observe()
        args.observe.parent.mkdir(parents=True, exist_ok=True)
        with args.observe.open('x') as stream:
            json.dump(value, stream, sort_keys=True, indent=2)
            stream.write('\n')


if __name__ == '__main__':
    main()
